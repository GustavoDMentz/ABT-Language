@testset "Pseudo Julia 0.3" begin
 @test run("numeros=[10,20,30,40,50]\nmostrar media de numeros onde valor é maior que 20") == ["40.0"]
 @test run("numbers=[10,20,30,40,50]\nshow average of numbers where value is above 20") == ["40.0"]
 @test run("if 2 is above 1 { show \"yes\" } else { show \"no\" }") == ["yes"]
 @test run("for each x in [1,2,3] { show x }") == ["1", "2", "3"]
 @test occursin("pseudo_average", generate(parse_program(tokenize("show average of [1,2,3]"))))
 @test_throws ErrorException run("show unknown")
 @test run("mostrar soma de [1,2,3,4] onde valor é maior que 2") == ["7"]
 @test lower_ir(parse_program(tokenize("show 42")))[1].op == :print
 @test lower_ir(parse_program(tokenize("show sum of [1,2,3]")))[1].operands[1].op == :aggregate
 for file in ("examples/portugues.pseudo", "examples/english.pseudo")
  src = read(joinpath(@__DIR__, "..", file), String)
  io = IOBuffer()
  explain(src; io=io)
  report = String(take!(io))
  @test all(occursin(header, report) for header in ("TOKENS", "AST", "IR", "GENERATED JULIA"))
  @test occursin("aggregate", report)
  @test occursin("println", report)
 end
end

