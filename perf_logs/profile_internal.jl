path = ARGS[1]
t0 = time_ns()
include(joinpath(@__DIR__, "..", "src", "ABT.jl"))
t1 = time_ns()
source = read(path, String)
t2 = time_ns()
tokens = ABT.tokenize(source)
t3 = time_ns()
ast = ABT.parse_program(tokens)
t4 = time_ns()
ir = ABT.lower_ir(ast)
t5 = time_ns()
ABT.validate_ir(ir)
t6 = time_ns()
result = ABT.execute(ast)
t7 = time_ns()
foreach(println, result)
t8 = time_ns()
for (name, a, b) in (("include", t0, t1), ("read", t1, t2), ("tokenize", t2, t3), ("parse", t3, t4), ("lower", t4, t5), ("validate", t5, t6), ("execute", t6, t7), ("print", t7, t8))
    println(stderr, "ABT_PROFILE ", name, " ", (b-a)/1e9)
end
